/** Inline identicon avatars keep the preview independent of the network. */
function avatar(initial: string, background: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="60" height="60"><rect width="60" height="60" rx="30" fill="${background}"/><text x="30" y="38" text-anchor="middle" font-family="system-ui, sans-serif" font-size="24" font-weight="600" fill="#15150f">${initial}</text></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

